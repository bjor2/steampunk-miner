/**
 * The planet registry (GD lock R1 on #302, 6306854642, with its addendum 6306861669; HS on #305,
 * 6306847681): `ores.economy.json` `planets.rows`, one row per planet from planet 1 with no gap.
 * The row that names a planet's species pool (ticket 542) also holds its radius, so a new planet
 * is one data row, never a second table. The kernel reads every row through its one `planetRow`
 * provider (`planetRowProvider.ts`, GD lock on #707): the generated row first, these fields on top.
 *
 * - `pool`: the species pool the planet's kind slots resolve to. Pools run from planet 1 with no
 *   gap; a row past the last pooled planet has none, so a slot there binds no species (#453).
 * - `radius`: the planet's frozen radius override with its ore rules key and reason, held to
 *   `radiusRule` (`frozenRadii.ts`). Radius changes only how long a planet takes, never hardness,
 *   ore value per cell, the drill law or prices (R1).
 * - `measuredMinutes`: the minutes the paired 3-seed run measured at the row's radius, null until
 *   the re-baseline (ticket 644) measures it.
 * - `radiusShrinkWhy`: why the radius is below the planet before it in its solar system
 *   (`frozenRadii.ts`).
 * - `hazard`: the planet's own hazard (ticket 651, `planetHazards.ts`), on planets 2 to 5 and never
 *   on planet 1; its kind is a row of `planets.hazards` (`hazardKinds.ts`).
 * - `name`: the planet's display name (ticket 702, `planetNames.ts`) on every planet before
 *   `planets.generatedNames.fromPlanet`; later planets take a generated one.
 * - `look`: the planet's rock tint, horizon and sky band (ticket 653, `planetLooks.ts`), on planets
 *   2 to 5 and never on planet 1.
 *
 * World generation reads the radius from ticket 643 and the hazard pockets from ticket 652.
 */
import type {
  FrozenRadius,
  PlanetLook,
  PlanetRowFields,
} from '../../../systems/registries/planetRow'
import {
  frozenRadiusOf,
  frozenRadiusProblems,
  isReason,
  radiusRuleProblems,
  shrinkProblems,
  type PlanetRowContext,
} from './frozenRadii'
import { hazardCapsOf, hazardKindsOf, type HazardCaps, type HazardKinds } from './hazardKinds'
import { planetHazardOf, planetHazardProblems, type PlanetHazard } from './planetHazards'
import {
  generatedPlanetNameOf,
  generatedPlanetNamesOf,
  planetNameProblems,
  type GeneratedPlanetNames,
} from './planetNames'
import { planetLookOf, planetLookProblems } from './planetLooks'

export type { PlanetRowContext } from './frozenRadii'

/** A planet's row as `ores.economy.json` authors it. */
export interface AuthoredPlanetRow {
  planetIndex: number
  /** The planet's display name; null on a planet the generator names. */
  name: string | null
  /** The species pool id; null past the last pooled planet. */
  pool: string | null
  radius: FrozenRadius
  /** Null until a paired run measures the planet at this radius. */
  measuredMinutes: number | null
  /** Why the radius is below the previous planet's in its solar system; null when it is not. */
  radiusShrinkWhy: string | null
  /** The planet's hazard (ticket 651); null on planet 1 and on any planet past the designed ones. */
  hazard: PlanetHazard | null
  /** The planet's own look (ticket 653); null on planet 1 and past the designed planets. */
  look: PlanetLook | null
}

/** R(p) = round(baseTiles + lnCoefficient * ln p), the rule the frozen rows were generated by. */
export interface RadiusRule {
  baseTiles: number
  lnCoefficient: number
  /** The lowest and highest k a retune may move the shared coefficient to (GD addendum). */
  lnCoefficientBounds: readonly [number, number]
}

export interface PlanetRows {
  radiusRule: RadiusRule
  /** Planet 1 first, one row per planet. */
  rows: readonly AuthoredPlanetRow[]
  /** The hazard kinds a row may name, by id (ticket 651). */
  hazards: HazardKinds
  /** The most any one hazard contact, and a whole dive, may cost. */
  hazardCaps: HazardCaps
  /** How a planet with no name on its row, or past the last row, is named (ticket 702). */
  generatedNames: GeneratedPlanetNames
}

type Raw = Record<string, unknown>

const PATH = 'ore.planets'
/** A pool id is kebab-case, as a `materials.json` row writes its `pool`. */
const POOL_ID = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/
const ROW_FIELDS = [
  'planet',
  'name',
  'pool',
  'radius',
  'measuredMinutes',
  'radiusShrinkWhy',
  'hazard',
  'look',
]
const FIRST_PLANET = 1

/** Why the `planets` block is not the planet registry; empty when it is. */
export function planetRowProblems(planets: unknown, context: PlanetRowContext): string[] {
  if (!isPlainMap(planets)) return [`${PATH} must hold a radiusRule and rows`]
  return [
    ...radiusRuleProblems(planets.radiusRule),
    ...rowListProblems(planets.rows, context),
    ...planetHazardProblems(planets, planets.rows),
    ...planetNameProblems(planets, planets.rows),
    ...planetLookProblems(planets.rows),
  ]
}

/** The block as typed rows; call only on a block `planetRowProblems` accepts. */
export function planetRowsOf(planets: Raw): PlanetRows {
  const rule = planets.radiusRule as Raw
  const [lowest, highest] = rule.lnCoefficientBounds as number[]
  return {
    radiusRule: {
      baseTiles: rule.baseTiles as number,
      lnCoefficient: rule.lnCoefficient as number,
      lnCoefficientBounds: [lowest, highest],
    },
    rows: (planets.rows as Raw[]).map(authoredRowOf),
    hazards: hazardKindsOf(planets.hazards as Raw),
    hazardCaps: hazardCapsOf(planets.hazardCaps as Raw),
    generatedNames: generatedPlanetNamesOf(planets.generatedNames as Raw),
  }
}

/** The fields the planet's row lays over the kernel's generated one; past the last row, its name. */
export function planetRowFieldsOf(planets: PlanetRows, planetIndex: number): PlanetRowFields {
  const row = planets.rows[planetIndex - FIRST_PLANET]
  return {
    displayName: nameOfPlanet(planets, planetIndex),
    poolId: row?.pool ?? null,
    look: row?.look ?? null,
    radius: row?.radius ?? null,
  }
}

/** The planet's frozen radius in tiles, or null past the registry's last row. */
export function radiusTilesOfPlanet(planets: PlanetRows, planetIndex: number): number | null {
  return planets.rows[planetIndex - FIRST_PLANET]?.radius.tiles ?? null
}

/** The planet's display name: its row's, or the generated one past the named rows. */
export function nameOfPlanet(planets: PlanetRows, planetIndex: number): string {
  const rowName = planets.rows[planetIndex - FIRST_PLANET]?.name ?? null
  return rowName ?? generatedPlanetNameOf(planets.generatedNames, planetIndex)
}

/** The planet's own look, or null where its row holds none or past the registry's last row. */
export function lookOfPlanet(planets: PlanetRows, planetIndex: number): PlanetLook | null {
  return planets.rows[planetIndex - FIRST_PLANET]?.look ?? null
}

/** Planet index to pool id, for every planet that has a pool. */
export function poolByPlanetOf(planets: PlanetRows): ReadonlyMap<number, string> {
  const pooled = planets.rows.filter((row) => row.pool !== null)
  return new Map(pooled.map((row) => [row.planetIndex, row.pool as string]))
}

/** The planets an unchecked block gives a pool, as the keys an earlier-pools table names them by. */
export function pooledPlanetKeysOf(planets: unknown): string[] {
  const rows = isPlainMap(planets) && Array.isArray(planets.rows) ? (planets.rows as unknown[]) : []
  return rows
    .filter((row): row is Raw => isPlainMap(row) && isPoolId(row.pool))
    .map((row) => String(row.planet))
}

/** The pool ids an unchecked block's rows name, as a pool's own kind slot may name them. */
export function poolIdsOf(planets: unknown): string[] {
  const rows = isPlainMap(planets) && Array.isArray(planets.rows) ? (planets.rows as unknown[]) : []
  return rows.filter(isPlainMap).flatMap((row) => (isPoolId(row.pool) ? [row.pool] : []))
}

export function isPoolId(pool: unknown): pool is string {
  return typeof pool === 'string' && POOL_ID.test(pool)
}

export function isPlainMap(value: unknown): value is Raw {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function authoredRowOf(row: Raw): AuthoredPlanetRow {
  return {
    planetIndex: row.planet as number,
    name: (row.name as string | undefined) ?? null,
    pool: (row.pool as string | undefined) ?? null,
    radius: frozenRadiusOf(row.radius as Raw),
    measuredMinutes: row.measuredMinutes as number | null,
    radiusShrinkWhy: (row.radiusShrinkWhy as string | undefined) ?? null,
    hazard: planetHazardOf(row),
    look: planetLookOf(row),
  }
}

function rowListProblems(rows: unknown, context: PlanetRowContext): string[] {
  if (!Array.isArray(rows) || rows.length === 0) return [`${PATH}.rows must list planets from 1`]
  const list = rows.map((row) => (isPlainMap(row) ? row : {}))
  const shapeProblems = [
    ...list.flatMap((row, at) => rowShapeProblems(row, at)),
    ...poolRunProblems(list),
  ]
  return shapeProblems.length > 0 ? shapeProblems : shrinkProblems(list, context)
}

function rowShapeProblems(row: Raw, at: number): string[] {
  const where = `${PATH}.rows[${at}]`
  const planet = at + FIRST_PLANET
  return [
    ...(row.planet === planet ? [] : [`${where}.planet must be ${planet}: planets 1 to n, no gap`]),
    ...(row.pool === undefined || isPoolId(row.pool) ? [] : [`${where}.pool must be a pool id`]),
    ...frozenRadiusProblems(row.radius, where),
    ...(isMeasuredMinutes(row.measuredMinutes)
      ? []
      : [`${where}.measuredMinutes must be null or minutes above 0`]),
    ...(row.radiusShrinkWhy === undefined || isReason(row.radiusShrinkWhy)
      ? []
      : [`${where}.radiusShrinkWhy must say why`]),
    ...unknownFieldsOf(row).map((field) => `${where}.${field} is not a planet row field`),
  ]
}

/** Pools run from planet 1 with no gap, so only planets past the last pooled one bind none. */
function poolRunProblems(rows: readonly Raw[]): string[] {
  const firstWithout = rows.findIndex((row) => row.pool === undefined)
  if (firstWithout < 0) return []
  return rows
    .map((row, at) => ({ row, at }))
    .filter(({ row, at }) => at > firstWithout && row.pool !== undefined)
    .map(
      ({ at }) => `${PATH}.rows[${at}] has a pool after planet ${firstWithout + 1}, which has none`,
    )
}

function unknownFieldsOf(row: Raw): string[] {
  return Object.keys(row).filter((field) => !ROW_FIELDS.includes(field))
}

function isMeasuredMinutes(minutes: unknown): boolean {
  return (
    minutes === null || (typeof minutes === 'number' && Number.isFinite(minutes) && minutes > 0)
  )
}
